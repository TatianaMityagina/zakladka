import type { Chapter } from '../types.js';

/**
 * Служебные разделы: не сюжет, а аннотация, глоссарий, иллюстрации и т.п.
 * Их не пересказываем и не спрашиваем по ним в тестах (модель честно отвечает
 * «это аннотация, а не глава»), но оставляем в поиске — список имён полезен для вопросов.
 * Определяем по заголовку на лету — работает и для уже загруженных книг.
 */
const EXTRA_TITLE =
  /^(аннотация|annotation|содержание|оглавление|от автора|от переводчика|от редакции|об авторе|благодарност|предисловие переводчика|имена персонажей|список персонажей|действующие лица|персонажи|профили персонажей|глоссарий|словарь|примечани|комментари|иллюстрации|copyright|копирайт|титул|информация о|выходные данные)/i;

export const isExtra = (ch: Pick<Chapter, 'title'>) => EXTRA_TITLE.test(ch.title.replace(/^[\s\d.·-]+/, ''));

/** По умолчанию закладка — после служебных разделов в начале: их «прочитали», открыв книгу */
export function leadingExtras(chapters: Chapter[]): number {
  let n = 0;
  while (n < chapters.length && isExtra(chapters[n])) n++;
  return n;
}
